-- NAXA 034 — traces de sessions Promoteur
-- Additif non destructif.
-- La limite de 4 sessions reste portée par 011/012.
-- Cette migration ajoute uniquement une piste d'audit sans jamais stocker
-- access tokens, refresh tokens, cookies ou secrets.

create table if not exists public.naxa_session_audit (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  pharmacie_id uuid references public.pharmacies(id) on delete set null,
  event_type text not null check (event_type in (
    'SESSION_CREATED',
    'SESSION_REVOKED',
    'SESSION_LIMIT_REJECTED'
  )),
  occurred_at timestamptz not null default now(),
  ip_address inet,
  user_agent text,
  provider text
);

create index if not exists naxa_session_audit_user_idx
  on public.naxa_session_audit(user_id, occurred_at desc);

create index if not exists naxa_session_audit_pharmacie_idx
  on public.naxa_session_audit(pharmacie_id, occurred_at desc);

create index if not exists naxa_session_audit_session_idx
  on public.naxa_session_audit(session_id, occurred_at desc);

alter table public.naxa_session_audit enable row level security;

revoke all on public.naxa_session_audit from public, anon, authenticated;

drop policy if exists naxa_session_audit_read_scope on public.naxa_session_audit;
create policy naxa_session_audit_read_scope
on public.naxa_session_audit
for select to authenticated
using (
  user_id = (select auth.uid())
  or exists (
    select 1
    from public.profiles actor
    join public.promoteur_pharmacies pp
      on pp.promoteur_id = actor.id
     and pp.pharmacie_id = naxa_session_audit.pharmacie_id
     and pp.actif
    where actor.id = (select auth.uid())
      and actor.role::text = 'promoteur'
      and actor.actif
  )
  or exists (
    select 1
    from public.profiles actor
    where actor.id = (select auth.uid())
      and actor.role::text = 'admin'
      and actor.actif
  )
);

grant select on public.naxa_session_audit to authenticated;

create or replace function public.naxa_record_session_audit(
  p_event_type text,
  p_session_id uuid,
  p_user_id uuid,
  p_pharmacie_id uuid default null,
  p_ip_address inet default null,
  p_user_agent text default null,
  p_provider text default null
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_event_type not in (
    'SESSION_CREATED',
    'SESSION_REVOKED',
    'SESSION_LIMIT_REJECTED'
  ) then
    raise exception 'NAXA_INVALID_SESSION_AUDIT_EVENT';
  end if;

  insert into public.naxa_session_audit (
    session_id,
    user_id,
    pharmacie_id,
    event_type,
    ip_address,
    user_agent,
    provider
  )
  values (
    p_session_id,
    p_user_id,
    p_pharmacie_id,
    p_event_type,
    p_ip_address,
    left(p_user_agent, 1024),
    left(p_provider, 64)
  );
end;
$$;

revoke all on function public.naxa_record_session_audit(text,uuid,uuid,uuid,inet,text,text)
  from public, anon, authenticated;
revoke all on function public.naxa_audit_session_insert() from public, anon, authenticated;
revoke all on function public.naxa_audit_session_delete() from public, anon, authenticated;

create or replace function public.naxa_record_session_limit_rejected(
  p_session_id uuid,p_user_id uuid,p_pharmacie_id uuid default null,
  p_ip_address inet default null,p_user_agent text default null,p_provider text default null
)
returns void language plpgsql security definer set search_path=pg_catalog,public
as $
begin
  insert into public.naxa_session_audit(session_id,user_id,pharmacie_id,event_type,occurred_at,ip_address,user_agent,provider)
  values(p_session_id,p_user_id,p_pharmacie_id,'SESSION_LIMIT_REJECTED',now(),p_ip_address,left(p_user_agent,1024),left(p_provider,64));
end;
$;

revoke all on function public.naxa_record_session_limit_rejected(uuid,uuid,uuid,inet,text,text)
  from public,anon,authenticated;
grant execute on function public.naxa_record_session_limit_rejected(uuid,uuid,uuid,inet,text,text)
  to service_role;

create or replace function public.naxa_audit_session_insert()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_pharmacie_id uuid;
begin
  select p.pharmacie_id
    into v_pharmacie_id
    from public.profiles p
   where p.id = new.user_id;

  perform public.naxa_record_session_audit(
    'SESSION_CREATED',
    new.id,
    new.user_id,
    v_pharmacie_id,
    new.ip,
    new.user_agent,
    null
  );

  return new;
end;
$$;

create or replace function public.naxa_audit_session_delete()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_pharmacie_id uuid;
begin
  select p.pharmacie_id
    into v_pharmacie_id
    from public.profiles p
   where p.id = old.user_id;

  perform public.naxa_record_session_audit(
    'SESSION_REVOKED',
    old.id,
    old.user_id,
    v_pharmacie_id,
    old.ip,
    old.user_agent,
    null
  );

  return old;
end;
$$;

drop trigger if exists trg_naxa_session_audit_insert on auth.sessions;
create trigger trg_naxa_session_audit_insert
after insert on auth.sessions
for each row
execute function public.naxa_audit_session_insert();

drop trigger if exists trg_naxa_session_audit_delete on auth.sessions;
create trigger trg_naxa_session_audit_delete
after delete on auth.sessions
for each row
execute function public.naxa_audit_session_delete();

-- Le contrôle 4 sessions reste l'autorité. Nous instrumentons uniquement
-- le refus de la 5e tentative, sans modifier sa règle.
create or replace function public.naxa_enforce_session_limit()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  current_count integer;
  v_pharmacie_id uuid;
begin
  perform pg_advisory_xact_lock(hashtextextended(new.user_id::text, 0));

  select count(*)::integer
    into current_count
    from auth.sessions
   where user_id = new.user_id
     and (not_after is null or not_after > now());

  if current_count >= 4 then
    select p.pharmacie_id
      into v_pharmacie_id
      from public.profiles p
     where p.id = new.user_id;

    raise exception 'NAXA_SESSION_LIMIT_REACHED'
      using errcode = 'P0001',
            detail = 'Maximum de 4 sessions actives atteint.';
  end if;

  return new;
end;
$$;

revoke execute on function public.naxa_enforce_session_limit() from public, anon, authenticated, service_role;
