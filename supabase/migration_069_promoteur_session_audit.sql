-- NAXA 069 — traces de sessions (audit)
-- Additif, non destructif.
-- Le plafond de 4 sessions reste porté par 011/012 (inchangé).
-- Aucun access token, refresh token, cookie ni secret n'est stocké.
-- Règle : l'audit ne bloque JAMAIS une connexion ni une suppression de compte ;
-- toute défaillance laisse une trace (avertissement + table naxa_session_audit_failures).

create table if not exists public.naxa_session_audit (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  pharmacie_id uuid references public.pharmacies(id) on delete set null,
  event_type text not null check (event_type in (
    'SESSION_CREATED',
    'SESSION_REVOKED',
    'SESSION_LIMIT_REJECTED'
  )),
  occurred_at timestamptz not null default now(),
  ip_address inet,
  user_agent text,
  provider text
);

create index if not exists naxa_session_audit_user_idx
  on public.naxa_session_audit(user_id, occurred_at desc);
create index if not exists naxa_session_audit_pharmacie_idx
  on public.naxa_session_audit(pharmacie_id, occurred_at desc);
create index if not exists naxa_session_audit_session_idx
  on public.naxa_session_audit(session_id, occurred_at desc);

alter table public.naxa_session_audit enable row level security;
revoke all on public.naxa_session_audit from public, anon, authenticated;

drop policy if exists naxa_session_audit_read_scope on public.naxa_session_audit;
create policy naxa_session_audit_read_scope
on public.naxa_session_audit
for select to authenticated
using (
  user_id = (select auth.uid())
  or exists (
    select 1
    from public.profiles actor
    join public.promoteur_pharmacies pp
      on pp.promoteur_id = actor.id
     and pp.pharmacie_id = naxa_session_audit.pharmacie_id
     and pp.actif
    where actor.id = (select auth.uid())
      and actor.role::text = 'promoteur'
      and actor.actif
  )
  or exists (
    select 1
    from public.profiles actor
    where actor.id = (select auth.uid())
      and actor.role::text = 'admin'
      and actor.actif
  )
);

grant select on public.naxa_session_audit to authenticated;

-- Table de secours : trace des défaillances d'écriture de l'audit.
create table if not exists public.naxa_session_audit_failures (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  event_type text not null,
  session_id uuid,
  user_id uuid,
  error_message text
);

alter table public.naxa_session_audit_failures enable row level security;
revoke all on public.naxa_session_audit_failures from public, anon, authenticated;

drop policy if exists naxa_session_audit_failures_admin_read on public.naxa_session_audit_failures;
create policy naxa_session_audit_failures_admin_read
on public.naxa_session_audit_failures
for select to authenticated
using (
  exists (
    select 1
    from public.profiles actor
    where actor.id = (select auth.uid())
      and actor.role::text = 'admin'
      and actor.actif
  )
);

grant select on public.naxa_session_audit_failures to authenticated;

create or replace function public.naxa_record_session_audit(
  p_event_type text,
  p_session_id uuid,
  p_user_id uuid,
  p_pharmacie_id uuid default null,
  p_ip_address inet default null,
  p_user_agent text default null,
  p_provider text default null
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_event_type not in (
    'SESSION_CREATED',
    'SESSION_REVOKED',
    'SESSION_LIMIT_REJECTED'
  ) then
    raise exception 'NAXA_INVALID_SESSION_AUDIT_EVENT';
  end if;

  insert into public.naxa_session_audit (
    session_id, user_id, pharmacie_id, event_type,
    ip_address, user_agent, provider
  )
  values (
    p_session_id, p_user_id, p_pharmacie_id, p_event_type,
    p_ip_address, left(p_user_agent, 1024), left(p_provider, 64)
  );
end;
$$;

revoke all on function public.naxa_record_session_audit(text,uuid,uuid,uuid,inet,text,text)
  from public, anon, authenticated;

create or replace function public.naxa_record_session_limit_rejected(
  p_session_id uuid,
  p_user_id uuid,
  p_pharmacie_id uuid default null,
  p_ip_address inet default null,
  p_user_agent text default null,
  p_provider text default null
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  insert into public.naxa_session_audit (
    session_id, user_id, pharmacie_id, event_type, occurred_at,
    ip_address, user_agent, provider
  )
  values (
    p_session_id, p_user_id, p_pharmacie_id, 'SESSION_LIMIT_REJECTED', now(),
    p_ip_address, left(p_user_agent, 1024), left(p_provider, 64)
  );
end;
$$;

revoke all on function public.naxa_record_session_limit_rejected(uuid,uuid,uuid,inet,text,text)
  from public, anon, authenticated;
grant execute on function public.naxa_record_session_limit_rejected(uuid,uuid,uuid,inet,text,text)
  to service_role;

create or replace function public.naxa_audit_session_insert()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_pharmacie_id uuid;
  v_err text;
begin
  begin
    select p.pharmacie_id into v_pharmacie_id
      from public.profiles p where p.id = new.user_id;

    perform public.naxa_record_session_audit(
      'SESSION_CREATED', new.id, new.user_id, v_pharmacie_id,
      new.ip, new.user_agent, null
    );
  exception when others then
    v_err := sqlerrm;
    raise warning 'NAXA_SESSION_AUDIT_FAILED event=SESSION_CREATED session=% user=% : %',
      new.id, new.user_id, v_err;
    begin
      insert into public.naxa_session_audit_failures(event_type, session_id, user_id, error_message)
      values ('SESSION_CREATED', new.id, new.user_id, left(v_err, 500));
    exception when others then
      raise warning 'NAXA_SESSION_AUDIT_FAILURE_LOG_FAILED : %', sqlerrm;
    end;
  end;
  return new;
end;
$$;

create or replace function public.naxa_audit_session_delete()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_pharmacie_id uuid;
  v_err text;
begin
  -- Suppression en cascade d'un compte : l'utilisateur n'existe plus,
  -- la trace ne peut plus le référencer. On ne bloque pas et on ne bruite pas.
  if not exists (select 1 from auth.users u where u.id = old.user_id) then
    return old;
  end if;

  begin
    select p.pharmacie_id into v_pharmacie_id
      from public.profiles p where p.id = old.user_id;

    perform public.naxa_record_session_audit(
      'SESSION_REVOKED', old.id, old.user_id, v_pharmacie_id,
      old.ip, old.user_agent, null
    );
  exception when others then
    v_err := sqlerrm;
    raise warning 'NAXA_SESSION_AUDIT_FAILED event=SESSION_REVOKED session=% user=% : %',
      old.id, old.user_id, v_err;
    begin
      insert into public.naxa_session_audit_failures(event_type, session_id, user_id, error_message)
      values ('SESSION_REVOKED', old.id, old.user_id, left(v_err, 500));
    exception when others then
      raise warning 'NAXA_SESSION_AUDIT_FAILURE_LOG_FAILED : %', sqlerrm;
    end;
  end;
  return old;
end;
$$;

-- Les droits sont retirés APRÈS la création des fonctions.
revoke all on function public.naxa_audit_session_insert() from public, anon, authenticated;
revoke all on function public.naxa_audit_session_delete() from public, anon, authenticated;

drop trigger if exists trg_naxa_session_audit_insert on auth.sessions;
create trigger trg_naxa_session_audit_insert
after insert on auth.sessions
for each row execute function public.naxa_audit_session_insert();

drop trigger if exists trg_naxa_session_audit_delete on auth.sessions;
create trigger trg_naxa_session_audit_delete
after delete on auth.sessions
for each row execute function public.naxa_audit_session_delete();
